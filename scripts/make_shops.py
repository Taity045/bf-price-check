#!/usr/bin/env python3
"""Make src/shops.js from research/retailers.json: shops that work live, and shops known to block us.
data/live_status.json (repo) is applied on top: newer live checks, without edits to the research file.
Optional: --add NAME,CC,DOMAIN for a shop that passed a live check now (e.g. MediaMarkt).
Set RESEARCH=/path/to/retailers.json if the research folder is not in this checkout."""
import json, os, pathlib, sys
root = pathlib.Path(__file__).parent.parent
data = json.loads(pathlib.Path(os.environ.get("RESEARCH") or root / "research/retailers.json").read_text())
ov = json.loads((root / "data/live_status.json").read_text())
for r in data:
    r.update(ov["set"].get(r["name"], {}))
data += ov["add"]
works, blocked, seen = [], [], set()
for r in data:
    key = tuple(sorted(r["domains"]))
    entry = {"name": r["name"], "cc": r["country"], "d": [d.lower() for d in r["domains"]]}
    if r["live_status"] == "works":
        if key in seen: continue
        seen.add(key); works.append(entry)
    elif r["live_status"] in ("blocked", "js_only"):
        blocked.append(entry)
args = sys.argv[1:]
while args[:1] == ["--add"]:
    name, cc, dom = args[1].split(","); works.append({"name": name, "cc": cc, "d": [dom]}); args = args[2:]
out = {"works": works, "blocked": blocked}
(root / "src/shops.js").write_text("// Generated by scripts/make_shops.py from research/retailers.json + data/live_status.json. Do not edit.\nconst SHOP_LIST = " + json.dumps(out, ensure_ascii=False) + ";\n")
print(len(works), "work,", len(blocked), "blocked")
