#!/usr/bin/env python3
"""Make src/og_font.js: anti-aliased glyph bitmaps (Inter) for the share image renderer. Run once; output is committed."""
import base64, json, zlib, pathlib
from PIL import ImageFont, Image, ImageDraw
F = "/usr/share/fonts/truetype/sand-box/google/Inter/Inter-VariableFont_opsz,wght.ttf"
CHARS = "".join(chr(c) for c in range(32, 127)) + "£€–—…‘’“”·×→"
SIZES = {"h1": (76, 800), "h2": (56, 700), "b": (34, 500), "bb": (34, 700), "s": (26, 600)}
out = {}
for key, (px, wght) in SIZES.items():
    f = ImageFont.truetype(F, px)
    try:
        f.set_variation_by_axes([32 if px >= 40 else 24, wght])
    except Exception:
        f.set_variation_by_axes([wght])
    asc, desc = f.getmetrics()
    glyphs, blob = {}, bytearray()
    for ch in CHARS:
        l, t, r, b = f.getbbox(ch, anchor="ls")
        adv = f.getlength(ch)
        w, h = max(0, r - l), max(0, b - t)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            data = im.tobytes()
        else:
            data = b""
        glyphs[ch] = [len(blob), w, h, l, t, round(adv, 2)]
        blob += data
    out[key] = {"px": px, "asc": asc, "desc": desc, "g": glyphs, "d": base64.b64encode(zlib.compress(bytes(blob), 9)).decode()}
p = pathlib.Path(__file__).parent.parent / "src/og_font.js"
p.write_text("// Generated by scripts/make_og_font.py (Inter, SIL Open Font License). Do not edit.\nexport const OG_FONT = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(p, p.stat().st_size)
